"""
Packs every Blender mesh into one file for a single Roblox Studio import.

Roblox only lets a client build a handful of meshes at runtime (EditableMesh
has a tiny client memory budget), so the game ships its Blender models as
uploaded mesh assets instead. This script merges assets/blender/glb/*.glb
(written by build_props.py, build_buildings.py, build_interiors.py and
build_monsters.py) into

    assets/blender/CannibalFamilyMeshes.glb   (BH_OUT renames it)

with one object per mesh part, named "<MeshName>_<material>", every mesh
around the same origin it was modelled at, plus two 1-stud cubes:
"MeshOrigin" at that origin and "MeshAxisX" 10 studs along +X, which tell
how the importer moved and turned the scene. Import it in Studio; then
tools/roblox/harvest_meshes.luau (run in the command bar or through the
Studio MCP) uses MeshOrigin to undo any move or scale the importer applied
and files the parts under ReplicatedStorage.MeshAssets.<MeshName>.

It also writes src/shared/MeshCatalog.luau: the Roblox material and
transparency of every palette material, which the client applies to the
imported parts.

    blender -b --factory-startup -P tools/blender/export_combined.py [-- Name ...]
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bpy  # noqa: E402
import bmesh  # noqa: E402

import build_props as bp  # noqa: E402
import build_buildings  # noqa: E402,F401  (adds the building palette entries)
import build_monsters  # noqa: E402,F401  (adds the cannibal palette entries)
import build_interiors  # noqa: E402,F401  (adds the room palette entries)
import build_house_parts  # noqa: E402,F401  (adds the farmhouse parts' palette entries)
import build_lobby  # noqa: E402,F401  (adds the truck stop palette entries)

# BH_OUT names the file, so a later batch can sit next to the first one
OUT = os.path.join(bp.ROOT, "assets", "blender", os.environ.get("BH_OUT", "CannibalFamilyMeshes.glb"))
CATALOG = os.path.join(bp.ROOT, "src", "shared", "MeshCatalog.luau")


def write_catalog():
    lines = [
        "--!strict",
        "-- Generated by tools/blender/export_combined.py - do not edit by hand.",
        "-- Roblox material and transparency for each Blender palette material; imported",
        '-- mesh parts are named "<MeshName>_<material>" (client MeshLibrary).',
        "",
        "export type Entry = { material: string, transparency: number }",
        "",
        "local catalog: { [string]: Entry } = {",
    ]
    for key in sorted(bp.PALETTE):
        pal = bp.PALETTE[key]
        lines.append(f'\t{key} = {{ material = "{pal["roblox"]}", transparency = {pal.get("transparency", 0)} }},')
    lines += ["}", "", "return catalog", ""]
    with open(CATALOG, "w") as f:
        f.write("\n".join(lines))


def main():
    argv = sys.argv
    only = set(argv[argv.index("--") + 1:]) if "--" in argv else set()
    bpy.ops.wm.read_factory_settings(use_empty=True)
    files = sorted(n for n in os.listdir(bp.GLB_DIR) if n.endswith(".glb"))
    count = 0
    for name in files:
        mesh_name = name[:-4]
        if only and mesh_name not in only:
            continue
        before = set(bpy.data.objects)
        bpy.ops.import_scene.gltf(filepath=os.path.join(bp.GLB_DIR, name))
        for ob in set(bpy.data.objects) - before:
            if ob.type != "MESH":
                bpy.data.objects.remove(ob, do_unlink=True)
                continue
            # keep "<MeshName>_<material>" even if the importer added a suffix
            base = ob.name.split(".")[0]
            ob.name = base if base.startswith(mesh_name + "_") else mesh_name + "_" + base
            count += 1
    # reference cubes the harvest script measures: one at the origin, one 10
    # studs along +X (Roblox) to recover any turn the importer applies
    for name, x in (("MeshOrigin", 0.0), ("MeshAxisX", 10.0)):
        bm = bmesh.new()
        bmesh.ops.create_cube(bm, size=1.0)
        bmesh.ops.translate(bm, vec=(x, 0, 0), verts=bm.verts)
        marker = bp.link(name, bm)
        marker.name = name
    for ob in bpy.context.scene.objects:
        ob.select_set(True)
    bpy.ops.export_scene.gltf(filepath=OUT, export_format="GLB", use_selection=True, export_apply=True, export_vertex_color="ACTIVE")
    write_catalog()
    print(f"[combined] {count} mesh parts from {len(files)} files -> {OUT}")


if __name__ == "__main__":
    main()
